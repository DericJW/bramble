#!/usr/bin/env node
/**
 * Finishes `expo export -p web` for GitHub Pages:
 *
 * - points the icon and manifest links at the app's folder (EXPO_BASE_URL, e.g. /hedgerow);
 * - adds a service worker that keeps a copy of the whole app, so the Home Screen app opens
 *   with no internet connection;
 * - copies index.html to 404.html, so links like /hedgerow/money open the app too;
 * - adds .nojekyll so GitHub serves folders whose names start with "_".
 *
 * Usage: EXPO_BASE_URL=/hedgerow npx expo export -p web && EXPO_BASE_URL=/hedgerow node scripts/build-pages.mjs
 */
import { createHash } from 'node:crypto';
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const BASE = (process.env.EXPO_BASE_URL ?? '').replace(/\/+$/, '');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

// 1. Links in index.html that start at the domain root.
const indexPath = join(DIST, 'index.html');
let html = readFileSync(indexPath, 'utf8');
if (BASE) {
  const skip = BASE.slice(1) + '/';
  html = html.replace(/(href|src)="\/(?!\/)([^"]*)"/g, (m, attr, rest) => (rest.startsWith(skip) ? m : `${attr}="${BASE}/${rest}"`));
}

// 2. The web app manifest.
const manifestPath = join(DIST, 'manifest.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
manifest.start_url = `${BASE}/`;
manifest.scope = `${BASE}/`;
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));

// 3. Register the service worker.
const register = `<script>if("serviceWorker"in navigator){addEventListener("load",function(){navigator.serviceWorker.register("${BASE}/sw.js",{scope:"${BASE}/"}).catch(function(){})})}</script>`;
html = html.replace('</body>', `${register}</body>`);
writeFileSync(indexPath, html);

// 4. The service worker, with every file of this build listed so it can be stored up front.
const files = walk(DIST)
  .map((f) => relative(DIST, f).split(sep).join('/'))
  .filter((f) => !['sw.js', '404.html', '.nojekyll'].includes(f))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const precache = [`${BASE}/`, ...files.map((f) => `${BASE}/${f}`)];

const sw = `// Generated by scripts/build-pages.mjs. Keeps Hedgerow working offline.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(BASE)};
const APP_CACHE = 'hedgerow-app-' + VERSION;
const FONT_CACHE = 'hedgerow-fonts';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(APP_CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('hedgerow-app-') && k !== APP_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Fonts from Google Fonts: keep a copy the first time they load.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(
      caches.open(FONT_CACHE).then((cache) =>
        cache.match(req).then(
          (hit) =>
            hit ||
            fetch(req).then((res) => {
              if (res.ok || res.type === 'opaque') cache.put(req, res.clone());
              return res;
            }),
        ),
      ),
    );
    return;
  }

  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + '/')) return;

  // Opening the app: try for the newest version, fall back to the stored one when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(APP_CACHE).then((cache) => cache.put(BASE + '/', copy));
          }
          return res;
        })
        .catch(() => caches.match(BASE + '/').then((hit) => hit || caches.match(BASE + '/index.html'))),
    );
    return;
  }

  // Everything else (scripts, images): stored copy first.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(APP_CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);

// 5. Deep links and Jekyll.
copyFileSync(indexPath, join(DIST, '404.html'));
writeFileSync(join(DIST, '.nojekyll'), '');

console.log(`GitHub Pages build ready in ${DIST}/ (base "${BASE || '/'}", ${files.length} files, version ${version}).`);
